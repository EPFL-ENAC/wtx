"""Wrapper around the workmux binary (github.com/raine/workmux).

workmux makes the worktrees and the tmux sessions. Every call to it is here.
The rules:

- Only `add` and `open` take --config, and workmux remembers nothing about it.
  `remove` and `close` read the config they find on disk, from their cwd up.
  So wtx writes the config it generates to <main>/.workmux.yaml and runs every
  workmux command from the main checkout. A .workmux.yaml on a feature branch
  then never changes what wtx runs: setup reads everything from the main
  checkout.
- `add`, `open` and `remove` have no JSON output. Read the exit code and
  stderr, and ask git for the path, never workmux.
- Always pass the name: --name to `add`, --target-name to `open` when the
  folder is not the handle. workmux slugifies names, and wtx computes the
  session name itself (context.session_name).
- `remove` always gets --keep-branch. Without it workmux deletes the branch,
  and on a terminal asks a question about an unmerged one. Deleting the
  branch is `wtx land`'s call.
"""

from __future__ import annotations

import json
from pathlib import Path

from . import git
from .config import WtxConfig
from .context import handle, session_prefix
from .proc import capture_code, is_dry_run, run

CONFIG_NAME = ".workmux.yaml"
# The first line of the file wtx writes. A .workmux.yaml without it was made
# by someone else, and wtx refuses to overwrite it.
MARKER = "# generated by wtx from wtx.toml"
HEADER = (
    f"{MARKER}. Do not edit: `wtx go` writes it again.\n"
    "# wtx passes it to workmux, a copy on a branch has no effect.\n"
)
# The window every session opens on. land.py and review.py add theirs next to it.
WINDOW = "dev"


# Only the status hooks: the skills workmux also ships include `merge`, which
# merges locally and removes the worktree, around `wtx land`. It asks a
# question, so it needs a terminal.
SETUP_HOOKS = ("workmux", "setup", "--hooks")


class WorkmuxError(Exception):
    pass


def hooks_installed(settings_text: str) -> bool:
    """workmux's status hooks, in ~/.claude/settings.json or as its Claude
    plugin. Without them `workmux dashboard` shows no agent state."""
    return "workmux set-window-status" in settings_text or '"workmux-status@' in settings_text


def available() -> bool:
    from .proc import which

    return which("workmux") is not None


def version() -> str:
    code, out, _ = capture_code(["workmux", "--version"])
    return out if code == 0 else ""


def config_path(main: Path) -> Path:
    return main / CONFIG_NAME


def _split_percent(position: int, total: int) -> int:
    """Size for the new pane so the right column ends up in equal parts."""
    remaining = total - position + 1
    return round(100 * remaining / (remaining + 1))


def pane_line(name: str) -> str:
    """What workmux types in a pane. `wtx pane` decides the rest, at run time."""
    from shlex import quote

    return f'eval "$(wtx pane {quote(name)})"'


def render_config(cfg: WtxConfig, repo: str) -> str:
    """The workmux config for a repo. It depends on wtx.toml only.

    Nothing per worktree or per call goes in it, so two `wtx go` at once
    cannot disturb each other. The agent pane comes first and has the focus,
    the others make a column on its right, as wtx did itself before.
    """
    panes = list(cfg.panes.panes)
    ordered = [p for p in panes if p.role == "agent"] + [p for p in panes if p.role != "agent"]
    rest = len(ordered) - 1
    out_panes: list[dict] = []
    for index, pane in enumerate(ordered):
        entry: dict = {"command": pane_line(pane.name)}
        if index == 0:
            entry["focus"] = True
        elif index == 1:
            entry["split"] = "horizontal"
            entry["percentage"] = 50
        else:
            entry["split"] = "vertical"
            entry["percentage"] = _split_percent(index, rest)
        out_panes.append(entry)
    data: dict = {
        "worktree_dir": ".claude/worktrees",
        "mode": "session",
        "window_prefix": session_prefix(repo),
        # workmux guesses the main branch from main/master, and a repo on
        # dev has neither. It is the branch the main checkout holds.
        "main_branch": cfg.repo.base_branch,
        "post_create": ["wtx hook post-create"],
        "pre_remove": ["wtx hook pre-remove"],
    }
    if out_panes:
        data["windows"] = [{"name": WINDOW, "panes": out_panes}]
    # JSON is YAML too, and the stdlib writes it.
    return HEADER + json.dumps(data, indent=2) + "\n"


def write_config(main: Path, cfg: WtxConfig, repo: str) -> Path:
    """Write <main>/.workmux.yaml from wtx.toml. Refuses a file wtx did not write."""
    from .agents.base import write_file  # agents imports repos, which imports this

    target = config_path(main)
    text = render_config(cfg, repo)
    if target.is_file():
        current = target.read_text(errors="replace")
        if current == text:
            return target
        if not current.startswith(MARKER):
            raise WorkmuxError(
                f"{target} was not written by wtx. wtx generates it from wtx.toml: "
                "move what you need into wtx.toml, then delete the file."
            )
    write_file(target, text)
    return target


def _run(args: list[str], cwd: Path) -> None:
    """Run workmux from the main checkout. Its output never reaches our caller."""
    if is_dry_run():
        run(["workmux", *args], cwd=cwd, mutating=True)
        return
    code, out, err = capture_code(["workmux", *args], cwd=cwd)
    if code != 0:
        message = err or out or f"workmux {' '.join(args)} failed"
        raise WorkmuxError(message)


def ensure(main: Path, branch: str, base: str) -> tuple[Path | None, bool]:
    """Worktree for branch, creating it as needed. Returns (path, existed_before).

    A new worktree fires the repo's `wtx hook post-create` from inside workmux.
    """
    existing = git.worktree_path_for(main, branch)
    if existing:
        return existing, True
    args = ["add", "--headless", "--config", str(config_path(main)), "--name", handle(branch)]
    if not git.branch_exists(main, branch):
        if git.branch_exists(main, f"origin/{branch}"):
            # workmux cuts a new branch from the base when only the remote one
            # exists. Make the local one first, so the work on origin is used.
            run(["git", "branch", "--quiet", "--track", branch, f"origin/{branch}"], cwd=main)
        else:
            args += ["--base", base]
    _run([*args, branch], main)
    return git.worktree_path_for(main, branch), False


def open_session(main: Path, path: Path, branch: str) -> None:
    """Build the session of a worktree that exists, in the background.

    A worktree made before workmux can have a folder that is not the handle
    (upper case, `_`, `.`). --target-name keeps the session name the one wtx
    computes.
    """
    args = ["open", "--background", "--config", str(config_path(main))]
    name = handle(branch)
    if path.name != name:
        args += ["--target-name", name]
    _run([*args, path.name], main)


def remove(main: Path, branch: str, *, force: bool = False) -> None:
    """Remove a worktree and its session, keep the branch.

    Fires the repo's `wtx hook pre-remove` first, from inside workmux.
    """
    path = git.worktree_path_for(main, branch)
    if path is None:
        raise WorkmuxError(f"no worktree for {branch}")
    args = ["remove", "--keep-branch"]
    if force:
        args.append("--force")
    else:
        # workmux refuses a worktree with any untracked file, sandbox stubs
        # included. Delete only the stubs: a --force here would also drop work
        # that arrived after the check.
        git.remove_empty_untracked(path)
    # No warning here: every caller reports a failure in its own words.
    _run([*args, path.name], main)
